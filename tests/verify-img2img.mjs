import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {runInNewContext,Script} from "node:vm";
const src=readFileSync("novelai-img2img.js","utf8"),html=readFileSync("index.html","utf8");new Script(src);
const ctx={module:{exports:{}}};runInNewContext(src,ctx);const api=ctx.module.exports;
const square=api.containRect(1000,500,1024,1024);
assert.equal(square.width,1024);assert.equal(square.height,512);assert.equal(square.y,256);assert.equal(square.padded,true);
const same=api.containRect(1024,1024,1024,1024);assert.equal(same.changed,false);assert.equal(same.padded,false);
const portrait=api.containRect(800,1200,1216,832);
assert.ok(portrait.width<=1216&&portrait.height<=832);assert.equal(portrait.padded,true);
assert.throws(()=>api.containRect(0,1,832,1216));
let b={action:"generate",parameters:{seed:2,width:832,height:1216,v4_prompt:{use_coords:true},reference_image_multiple:["vibe"]}};
api.apply(b,"YWJjZA==",0.5,0.1);
assert.equal(b.action,"img2img");assert.equal(b.parameters.image,"YWJjZA==");assert.equal(b.parameters.strength,0.5);assert.equal(b.parameters.noise,0.1);
assert.equal(b.parameters.seed,2);assert.equal(b.parameters.v4_prompt.use_coords,true);assert.equal(b.parameters.reference_image_multiple[0],"vibe");
assert.throws(()=>api.apply({parameters:{}},"bad",0.5,0.1));
assert.throws(()=>api.apply({parameters:{}},"YWJjZA==",1.2,0.1));
for(const id of ["img2drop","img2file","img2saved","img2preview","img2status","img2strength","img2noise","img2size","img2clear"])assert.ok(html.includes('id="'+id+'"'),id);
const panel=html.slice(html.indexOf('<dialog id="gd">'),html.indexOf('<dialog id="bd">'));
assert.ok(panel.indexOf('读取 NovelAI PNG 参数')<panel.indexOf('图生图（Image to Image）'));
assert.ok(panel.indexOf('图生图（Image to Image）')<panel.indexOf('保存与下载设置'));
assert.match(html,/NovelAIImageToImage\.apply\(body,base\.png/);
assert.match(html,/NovelAIImageToImage\.apply\(body,sharedImg2\.png/);
assert.match(html,/ctx\.drawImage\(img,r\.x,r\.y,r\.width,r\.height\)/);
assert.match(html,/img2SavedOptions\(\)/);
assert.match(html,/addEventListener\("paste"/);
assert.doesNotMatch(html,/yrhefhwmwirohbccoybm|sb_publishable_s_PM8ZRi/);
console.log("PASS Stage F: PNG base64 img2img API payload, strength/noise bounds, no crop/padded fitting, existing model parameters, UI, local source and both generation paths");
